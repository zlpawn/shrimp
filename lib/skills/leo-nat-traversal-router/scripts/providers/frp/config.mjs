import fs from "node:fs";
import path from "node:path";
import { getProviderPaths } from "../../core/system.mjs";

function tomlEscape(value) {
  return String(value ?? "").replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

export function getConfigPaths(overrideDir = null) {
  const { configDir } = getProviderPaths("frp", overrideDir);
  return {
    configDir,
    jsonPath: path.join(configDir, "config.json"),
    secretsPath: path.join(configDir, "secrets.json"),
    tomlPath: path.join(configDir, "frpc.toml"),
  };
}

export function loadConfig(overrideDir = null) {
  const { jsonPath, secretsPath } = getConfigPaths(overrideDir);

  let config = {
    serverAddr: "",
    serverPort: 7000,
    logLevel: "info",
    proxies: [],
  };

  let secrets = {
    token: "",
  };

  if (fs.existsSync(jsonPath)) {
    try {
      const parsed = JSON.parse(fs.readFileSync(jsonPath, "utf-8"));
      config = { ...config, ...parsed };
    } catch {
      // ignore parse error, fallback to defaults
    }
  }

  if (fs.existsSync(secretsPath)) {
    try {
      const parsed = JSON.parse(fs.readFileSync(secretsPath, "utf-8"));
      secrets = { ...secrets, ...parsed };
    } catch {
      // ignore
    }
  }

  return { config, secrets };
}

export function renderToml(config, secrets = {}) {
  const lines = [];
  lines.push(`# Generated by leo-nat-traversal-router`);
  lines.push(`# Docs: https://github.com/fatedier/frp`);
  lines.push(`serverAddr = "${tomlEscape(config.serverAddr || "127.0.0.1")}"`);
  lines.push(`serverPort = ${Number(config.serverPort) || 7000}`);

  if (secrets.token) {
    lines.push(`auth.token = "${tomlEscape(secrets.token)}"`);
  }

  lines.push(`log.to = "console"`);
  lines.push(`log.level = "${tomlEscape(config.logLevel || "info")}"`);
  lines.push("");

  const proxies = Array.isArray(config.proxies) ? config.proxies : [];
  for (const proxy of proxies) {
    lines.push(`[[proxies]]`);
    lines.push(`name = "${tomlEscape(proxy.name)}"`);
    lines.push(`type = "${tomlEscape(proxy.type || "tcp")}"`);
    lines.push(`localIP = "${tomlEscape(proxy.localIP || "127.0.0.1")}"`);
    lines.push(`localPort = ${Number(proxy.localPort)}`);

    if (proxy.type === "http" || proxy.type === "https") {
      if (proxy.customDomains && proxy.customDomains.length > 0) {
        const domains = (Array.isArray(proxy.customDomains) ? proxy.customDomains : [proxy.customDomains])
          .map((d) => `"${tomlEscape(d)}"`)
          .join(", ");
        lines.push(`customDomains = [${domains}]`);
      }
      if (proxy.subdomain) {
        lines.push(`subdomain = "${tomlEscape(proxy.subdomain)}"`);
      }
    } else {
      if (proxy.remotePort) {
        lines.push(`remotePort = ${Number(proxy.remotePort)}`);
      }
    }
    lines.push("");
  }

  return `${lines.join("\n").trim()}\n`;
}

export function saveConfig(config, secrets = null, overrideDir = null) {
  const { jsonPath, secretsPath, tomlPath } = getConfigPaths(overrideDir);

  fs.writeFileSync(jsonPath, JSON.stringify(config, null, 2), "utf-8");

  if (secrets !== null) {
    fs.writeFileSync(secretsPath, JSON.stringify(secrets, null, 2), {
      encoding: "utf-8",
      mode: 0o600, // protect sensitive token
    });
  } else {
    // load existing secrets if not provided
    const existing = loadConfig(overrideDir);
    secrets = existing.secrets;
  }

  const tomlContent = renderToml(config, secrets);
  fs.writeFileSync(tomlPath, tomlContent, "utf-8");

  return {
    config,
    tomlPath,
    hasToken: Boolean(secrets?.token),
  };
}

export function setServer({ serverAddr, serverPort, token, logLevel, dataDir }) {
  const { config, secrets } = loadConfig(dataDir);

  if (serverAddr !== undefined) config.serverAddr = String(serverAddr).trim();
  if (serverPort !== undefined) config.serverPort = Number(serverPort);
  if (logLevel !== undefined) config.logLevel = String(logLevel).trim();
  if (token !== undefined) secrets.token = String(token).trim();

  return saveConfig(config, secrets, dataDir);
}

export function addProxy({
  name,
  type = "tcp",
  localIP = "127.0.0.1",
  localPort,
  remotePort,
  customDomains,
  subdomain,
  dataDir,
}) {
  if (!name) throw new Error("Proxy name is required");
  if (!localPort) throw new Error("localPort is required");

  const { config, secrets } = loadConfig(dataDir);
  const existingIdx = config.proxies.findIndex((p) => p.name === name);

  const proxyItem = {
    name: String(name).trim(),
    type: String(type).trim().toLowerCase(),
    localIP: String(localIP).trim(),
    localPort: Number(localPort),
  };

  if (remotePort) proxyItem.remotePort = Number(remotePort);
  if (customDomains) {
    proxyItem.customDomains = Array.isArray(customDomains) ? customDomains : [customDomains];
  }
  if (subdomain) proxyItem.subdomain = String(subdomain).trim();

  if (existingIdx >= 0) {
    config.proxies[existingIdx] = proxyItem;
  } else {
    config.proxies.push(proxyItem);
  }

  return saveConfig(config, secrets, dataDir);
}

export function removeProxy(name, dataDir = null) {
  if (!name) throw new Error("Proxy name is required");
  const { config, secrets } = loadConfig(dataDir);
  const initialLen = config.proxies.length;
  config.proxies = config.proxies.filter((p) => p.name !== name);

  if (config.proxies.length === initialLen) {
    return { success: false, message: `Proxy '${name}' not found` };
  }

  saveConfig(config, secrets, dataDir);
  return { success: true, removed: name, remaining: config.proxies.length };
}

export function getPublicConfig(overrideDir = null) {
  const { config, secrets } = loadConfig(overrideDir);
  const { tomlPath } = getConfigPaths(overrideDir);

  return {
    serverAddr: config.serverAddr || "(not configured)",
    serverPort: config.serverPort || 7000,
    logLevel: config.logLevel || "info",
    hasToken: Boolean(secrets.token),
    tokenMasked: secrets.token ? `${secrets.token.slice(0, 3)}****` : "(none)",
    proxies: config.proxies,
    tomlPath,
  };
}
